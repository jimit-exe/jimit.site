export type LayerName = keyof typeof layers;

/** One SVG path per colour: each horizontal run of a colour becomes `M x y h w v1 h-w z`. */
export function layerPaths(name: LayerName): { cls: string; d: string }[] {
  const byColour = new Map<string, string[]>();
  layers[name].forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      if (ch !== '.') {
        const w = end - x;
        const list = byColour.get(ch) ?? [];
        list.push(`M${x} ${y}h${w}v1h-${w}z`);
        byColour.set(ch, list);
      }
      x = end;
    }
  });
  return [...byColour].map(([ch, parts]) => ({ cls: `px-${ch}`, d: parts.join('') }));
}
